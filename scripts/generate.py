#!/usr/bin/env python3
"""Generate every terminal color scheme from palettes/*.toml.

The palette TOML files are the single source of truth. Every file under
themes/ is generated by this script, so the terminals can never drift apart.

    python3 scripts/generate.py           # (re)write themes/
    python3 scripts/generate.py --check   # exit 1 if themes/ is out of date

Requires Python 3.11+ (tomllib).
"""
from __future__ import annotations

import argparse
import json
import plistlib
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PALETTES = ROOT / "palettes"
THEMES = ROOT / "themes"

ANSI_ORDER = [
    "black", "red", "green", "yellow", "blue", "magenta", "cyan", "white",
    "bright_black", "bright_red", "bright_green", "bright_yellow",
    "bright_blue", "bright_magenta", "bright_cyan", "bright_white",
]
COLOR_KEYS = [
    "background", "foreground", "selection", "comment", "cursor",
    "cursor_text", "red", "orange", "yellow", "green", "purple", "cyan", "pink",
]
HEX = re.compile(r"^#[0-9A-F]{6}$")


def load_palettes() -> list[dict]:
    palettes = []
    for path in sorted(PALETTES.glob("*.toml")):
        with path.open("rb") as fh:
            p = tomllib.load(fh)
        for section, keys in (("colors", COLOR_KEYS), ("ansi", ANSI_ORDER)):
            for key in keys:
                value = p[section][key]
                if not HEX.match(value):
                    sys.exit(f"{path.name}: [{section}] {key} = {value!r} is not #RRGGBB (uppercase)")
        if p["meta"]["slug"] != path.stem:
            sys.exit(f"{path.name}: meta.slug must equal the file name")
        palettes.append(p)
    return palettes


def header(p: dict, comment: str) -> str:
    m = p["meta"]
    kind = "official" if m["official"] else "derived, unofficial"
    return (
        f"{comment} {m['name']} ({kind}) - generated by scripts/generate.py from palettes/{m['slug']}.toml\n"
        f"{comment} Palette source: {m['source']}\n"
        f"{comment} Do not edit by hand. Part of grok-build-dracula (MIT).\n"
    )


def rgb(h: str) -> tuple[int, int, int]:
    return int(h[1:3], 16), int(h[3:5], 16), int(h[5:7], 16)


# ---------------------------------------------------------------- writers

def iterm2(p: dict) -> bytes:
    c, a = p["colors"], p["ansi"]

    def entry(h: str) -> dict:
        r, g, b = rgb(h)
        return {
            "Alpha Component": 1.0,
            "Blue Component": round(b / 255, 6),
            "Color Space": "sRGB",
            "Green Component": round(g / 255, 6),
            "Red Component": round(r / 255, 6),
        }

    d = {f"Ansi {i} Color": entry(a[k]) for i, k in enumerate(ANSI_ORDER)}
    d.update({
        "Background Color": entry(c["background"]),
        "Foreground Color": entry(c["foreground"]),
        "Bold Color": entry(c["foreground"]),
        "Cursor Color": entry(c["cursor"]),
        "Cursor Text Color": entry(c["cursor_text"]),
        "Cursor Guide Color": entry(c["selection"]),
        "Selection Color": entry(c["selection"]),
        "Selected Text Color": entry(c["foreground"]),
        "Link Color": entry(c["cyan"]),
        "Badge Color": entry(c["pink"]),
    })
    body = plistlib.dumps(d, sort_keys=True)
    note = f"<!-- {p['meta']['name']} - generated by scripts/generate.py from palettes/{p['meta']['slug']}.toml. Do not edit by hand. -->\n"
    first, rest = body.split(b"\n", 1)
    return first + b"\n" + note.encode() + rest


def ghostty(p: dict) -> str:
    c, a = p["colors"], p["ansi"]
    lines = [header(p, "#")]
    lines += [f"palette = {i}={a[k]}" for i, k in enumerate(ANSI_ORDER)]
    lines += [
        f"background = {c['background']}",
        f"foreground = {c['foreground']}",
        f"cursor-color = {c['cursor']}",
        f"cursor-text = {c['cursor_text']}",
        f"selection-background = {c['selection']}",
        f"selection-foreground = {c['foreground']}",
    ]
    return "\n".join(lines) + "\n"


def wezterm(p: dict) -> str:
    c, a = p["colors"], p["ansi"]
    q = lambda xs: "[" + ", ".join(f'"{x}"' for x in xs) + "]"  # noqa: E731
    return (
        header(p, "#")
        + "\n[colors]\n"
        + f'background = "{c["background"]}"\n'
        + f'foreground = "{c["foreground"]}"\n'
        + f'cursor_bg = "{c["cursor"]}"\n'
        + f'cursor_fg = "{c["cursor_text"]}"\n'
        + f'cursor_border = "{c["cursor"]}"\n'
        + f'selection_bg = "{c["selection"]}"\n'
        + f'selection_fg = "{c["foreground"]}"\n'
        + f'scrollbar_thumb = "{c["selection"]}"\n'
        + f'split = "{c["comment"]}"\n'
        + f"ansi = {q(a[k] for k in ANSI_ORDER[:8])}\n"
        + f"brights = {q(a[k] for k in ANSI_ORDER[8:])}\n"
        + "\n[metadata]\n"
        + f'name = "{p["meta"]["name"]}"\n'
        + 'origin_url = "https://github.com/rystedtcreative/grok-build-dracula"\n'
    )


def kitty(p: dict) -> str:
    c, a = p["colors"], p["ansi"]
    m = p["meta"]
    lines = [
        f"## name: {m['name']}",
        "## author: R Creative (palette: Dracula Theme, https://draculatheme.com)",
        "## license: MIT",
        "## upstream: https://github.com/rystedtcreative/grok-build-dracula",
        f"## blurb: {m['name']} for Grok Build's terminal theme ({m['appearance']})",
        "",
        header(p, "#"),
    ]
    lines += [
        f"foreground {c['foreground']}",
        f"background {c['background']}",
        f"selection_foreground {c['foreground']}",
        f"selection_background {c['selection']}",
        f"cursor {c['cursor']}",
        f"cursor_text_color {c['cursor_text']}",
        f"url_color {c['cyan']}",
        f"active_border_color {c['comment']}",
        f"inactive_border_color {c['selection']}",
        f"bell_border_color {c['orange']}",
        f"active_tab_foreground {c['foreground']}",
        f"active_tab_background {c['selection']}",
        f"inactive_tab_foreground {c['comment']}",
        f"inactive_tab_background {c['background']}",
        f"mark1_foreground {c['background']}",
        f"mark1_background {c['red']}",
    ]
    lines += [f"color{i} {a[k]}" for i, k in enumerate(ANSI_ORDER)]
    return "\n".join(lines) + "\n"


def alacritty(p: dict) -> str:
    c, a = p["colors"], p["ansi"]
    names = ["black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"]
    out = [header(p, "#")]
    out.append("[colors.primary]")
    out.append(f'background = "{c["background"]}"')
    out.append(f'foreground = "{c["foreground"]}"')
    out.append(f'bright_foreground = "{a["bright_white"]}"')
    out.append("\n[colors.cursor]")
    out.append(f'text = "{c["cursor_text"]}"')
    out.append(f'cursor = "{c["cursor"]}"')
    out.append("\n[colors.selection]")
    out.append(f'text = "{c["foreground"]}"')
    out.append(f'background = "{c["selection"]}"')
    out.append("\n[colors.normal]")
    out += [f'{n} = "{a[n]}"' for n in names]
    out.append("\n[colors.bright]")
    out += [f'{n} = "{a["bright_" + n]}"' for n in names]
    return "\n".join(out) + "\n"


def windows_terminal(p: dict) -> str:
    c, a = p["colors"], p["ansi"]
    wt = {
        "name": p["meta"]["name"],
        "background": c["background"],
        "foreground": c["foreground"],
        "cursorColor": c["cursor"],
        "selectionBackground": c["selection"],
    }
    keymap = {"magenta": "purple"}
    for k in ANSI_ORDER:
        base = k.removeprefix("bright_")
        base = keymap.get(base, base)
        key = ("bright" + base.capitalize()) if k.startswith("bright_") else base
        wt[key] = a[k]
    return json.dumps(wt, indent=4) + "\n"


TARGETS = {
    # dir name: (file name template, writer)
    "iterm2": ("grok-{slug}.itermcolors", iterm2),
    "ghostty": ("grok-{slug}", ghostty),
    "wezterm": ("grok-{slug}.toml", wezterm),
    "kitty": ("grok-{slug}.conf", kitty),
    "alacritty": ("grok-{slug}.toml", alacritty),
    "windows-terminal": ("grok-{slug}.json", windows_terminal),
}


def render_all() -> dict[Path, bytes]:
    files: dict[Path, bytes] = {}
    for p in load_palettes():
        for d, (tmpl, writer) in TARGETS.items():
            data = writer(p)
            if isinstance(data, str):
                data = data.encode()
            files[THEMES / d / tmpl.format(slug=p["meta"]["slug"])] = data
    return files


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if themes/ is stale")
    args = ap.parse_args()
    files = render_all()
    stale = []
    for path, data in files.items():
        if not path.exists() or path.read_bytes() != data:
            stale.append(path)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(data)
    expected = set(files)
    extra = [x for x in THEMES.rglob("*") if x.is_file() and x not in expected]
    if args.check:
        for x in stale:
            print(f"stale: {x.relative_to(ROOT)}")
        for x in extra:
            print(f"unexpected: {x.relative_to(ROOT)}")
        return 1 if (stale or extra) else 0
    for x in extra:
        x.unlink()
        print(f"removed: {x.relative_to(ROOT)}")
    print(f"generated {len(files)} files ({len(stale)} changed)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
